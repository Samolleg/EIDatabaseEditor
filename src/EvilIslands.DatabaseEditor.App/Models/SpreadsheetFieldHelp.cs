            "WeightType" => "Категория веса оружия, используемая при выборе бонусов навыков. Это не вес предмета в инвентаре.",
            "Exp" => "Количество опыта, заданное для прототипа в Lua.",
            "StatStrength" => "Значение силы прототипа в Lua.",
            "StatDexterity" => "Значение ловкости прототипа в Lua.",
            "StatIntelligence" => "Значение разума прототипа в Lua.",
            "Defense" => "Дополнительный параметр защиты от доспеха.",
            "Attack" => "Дополнительный параметр атаки от доспеха.",
            "Sight" => "Параметр заметности персонажа для противников.",
            "Hearing" => "Параметр слышимости персонажа для противников.",
            "cooldownSeconds" => "Время перезарядки умения в секундах.",
            "damageMultiplier" => "Множитель урона умения.",
            "charges" => "Количество зарядов расходника в правиле.",
            "registrationOnly" => "Только регистрация расходника из MOB; само правило не выдаёт его персонажу.",
            _ => $"{label}. Название взято из подключённой схемы Lua; подробная формула для этого поля здесь не описана."
        };
        if (spec.Name == "ForbiddenItems") meaning = "ID магазинов, где запрещено размножение предмета. Несколько ID вводятся через точку с запятой. Очистка ячейки удаляет запрет; 0 не означает запрет во всех магазинах.";
